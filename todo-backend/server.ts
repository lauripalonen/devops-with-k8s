import express from "express";
import { Pool } from "pg";

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3003;
const HOST = process.env.HOSTNAME || "0.0.0.0";
const pool = new Pool({
  host: process.env.POSTGRES_HOST || "localhost",
  port: process.env.POSTGRES_PORT
    ? parseInt(process.env.POSTGRES_PORT, 10)
    : 5432,
  database: process.env.POSTGRES_DB,
  user: process.env.POSTGRES_USER,
  password: process.env.POSTGRES_PASSWORD,
});

app.use(express.json());

async function initializeDatabase() {
  for (let attempt = 0; attempt < 15; attempt++) {
    try {
      await pool.query(`
        CREATE TABLE IF NOT EXISTS todos (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          todo TEXT NOT NULL
        )
      `);
      return;
    } catch (error) {
      if (attempt === 14) {
        throw error;
      }
      await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }
}

app.get("/", (req, res) => {
  res.send("<h1>Todo backend</h1>");
});

app.get("/todos", async (_req, res) => {
  const { rows } = await pool.query<{ todo: string }>(
    "SELECT todo FROM todos ORDER BY id ASC",
  );
  res.status(200).json(rows.map((row) => row.todo));
});

app.post("/todos", async (req, res) => {
  const todo: unknown = req.body?.todo;
  console.log(JSON.stringify({ event: "todo_received", todo }));

  if (typeof todo !== "string") {
    console.warn(
      JSON.stringify({ event: "todo_rejected", reason: "invalid_type", todo }),
    );
    res.status(400).send("Invalid todo item.");
    return;
  }

  if (todo.length > 140) {
    console.warn(
      JSON.stringify({
        event: "todo_rejected",
        reason: "too_long",
        length: todo.length,
        todo,
      }),
    );
    res.status(400).send(`Too long todo item: ${todo}`);
    return;
  }

  await pool.query("INSERT INTO todos (todo) VALUES ($1)", [todo]);

  console.log(JSON.stringify({ event: "todo_created", todo }));

  res.status(201).json({ message: "Todo item created successfully." });
});

async function startServer() {
  await initializeDatabase();
  app.listen(PORT, HOST, () => {
    console.log(`Server is running on http://${HOST}:${PORT}`);
  });
}

startServer().catch((error: unknown) => {
  console.error("Failed to initialize the todo database:", error);
  process.exit(1);
});
